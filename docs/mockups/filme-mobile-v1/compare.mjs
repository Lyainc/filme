import assert from 'node:assert/strict';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import puppeteer from 'puppeteer-core';
const dir = dirname(fileURLToPath(import.meta.url));
const output = resolve(dir, 'verification');
const before = process.env.FILME_BEFORE_URL || 'http://127.0.0.1:3792';
const after = process.env.FILME_MOCKUP_URL || 'http://127.0.0.1:3791/docs/mockups/filme-mobile-v1/index.html';
const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--no-sandbox'] });
try {
  const page = await browser.newPage();
  await page.setViewport({ width: 393, height: 659, isMobile: true, hasTouch: true, deviceScaleFactor: 1 });
  await page.setRequestInterception(true);
  page.on('request', r => /^https?:\/\/127\.0\.0\.1:379[12]\//.test(r.url()) || r.url().startsWith('data:') ? r.continue() : r.abort());
  await page.goto(before, { waitUntil: 'networkidle0' });
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({ path: resolve(output, 'before-home.png') });
  await page.evaluate(() => localStorage.setItem('filme:phototicket:v1', JSON.stringify({ movieInfo: { title: '먼 바다', titleOg: 'THE FAR SEA', releaseDate: '2025', actors: '윤재이, Élodie Marchand-Vasseur', runtime: '118', watchDate: '2026-02-14', watchTime: '19:40', theater: '메가박스 코엑스', screen: 'Dolby Cinema관', seat: 'H열 12번', rating: 4.5, signature: '지윤' }, components: { layout: 'minimal' }, fieldVisibility: {} })));
  await page.reload({ waitUntil: 'networkidle0' });
  await page.click('[data-testid="landing-restore"]');
  await page.waitForSelector('[data-ticket-scale-wrapper]');
  await page.evaluate(() => document.fonts.ready);
  await page.waitForFunction(() => document.querySelector('[data-ticket-scale-wrapper]').getBoundingClientRect().width < 400);
  await new Promise(r => setTimeout(r, 350));
  const baseline = await page.evaluate(() => ({ canvas: getComputedStyle(document.documentElement).getPropertyValue('--bg').trim(), ticket: document.querySelector('[data-ticket-scale-wrapper]').textContent }));
  assert(baseline.ticket.includes('먼 바다'));
  await page.screenshot({ path: resolve(output, 'before-editor.png') });
  await page.$eval('[role="toolbar"][aria-label="편집 도구"]', el => el.style.visibility = 'hidden');
  await (await page.$('[data-ticket-scale-wrapper]')).screenshot({ path: resolve(output, 'comparison-ticket.png') });
  await page.$eval('[role="toolbar"][aria-label="편집 도구"]', el => el.style.visibility = '');
  await page.click('[aria-label="티켓 항목 목록"]');
  await new Promise(r => setTimeout(r, 350));
  await page.screenshot({ path: resolve(output, 'before-fields.png') });
  await page.goto(after + '?scene=design', { waitUntil: 'networkidle0' });
  await page.$eval('.preview-ticket-button img', async img => { img.src = './verification/comparison-ticket.png'; await img.decode(); });
  await page.screenshot({ path: resolve(output, 'after-editor-same-ticket.png') });
  await page.click('[aria-label="뒤로 가기"]');
  await page.waitForSelector('[data-page="info"]');
  await page.screenshot({ path: resolve(output, 'after-fields.png') });
  await Bun.write(resolve(output, 'comparison.json'), JSON.stringify({ width: 393, height: 659, before, after, baseline, method: 'Same sample fields. Existing local app ticket DOM captured to comparison-ticket.png and reused unchanged in the mockup editor screenshot. Comparison image override is in browser memory only.', limitation: 'UI structure comparison, not a usability study or real-device test.' }, null, 2));
  console.log('Comparison captured with the same ticket and 393x659 viewport.');
} finally { await browser.close(); }
